-- Script de Creación e Inicialización de la Base de Datos
-- Base de Datos: agro_nacional

-- Crear base de datos si no existe
CREATE DATABASE IF NOT EXISTS `agro_nacional` DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE `agro_nacional`;

-- 1. Tabla de Estados
CREATE TABLE IF NOT EXISTS `estados` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `nombre` VARCHAR(100) NOT NULL
) ENGINE=InnoDB;

-- 2. Tabla de Municipios
CREATE TABLE IF NOT EXISTS `municipios` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `id_estado` INT NOT NULL,
  `nombre` VARCHAR(100) NOT NULL,
  FOREIGN KEY (`id_estado`) REFERENCES `estados`(`id`) ON DELETE CASCADE
) ENGINE=InnoDB;

-- 3. Tabla de Parroquias
CREATE TABLE IF NOT EXISTS `parroquias` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `id_municipio` INT NOT NULL,
  `nombre` VARCHAR(100) NOT NULL,
  FOREIGN KEY (`id_municipio`) REFERENCES `municipios`(`id`) ON DELETE CASCADE
) ENGINE=InnoDB;

-- 4. Tabla de Productores
CREATE TABLE IF NOT EXISTS `productores` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `nombre` VARCHAR(100) NOT NULL,
  `apellido` VARCHAR(100) NOT NULL,
  `cedula` VARCHAR(50) NOT NULL UNIQUE,
  `telefono` VARCHAR(50) NOT NULL,
  `email` VARCHAR(100) DEFAULT NULL,
  `activo` BOOLEAN DEFAULT TRUE,
  `fecha_registro` TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

-- 5. Tabla de Fincas (Sin la columna coordenadas)
CREATE TABLE IF NOT EXISTS `fincas` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `id_productor` INT NOT NULL,
  `id_parroquia` INT NOT NULL,
  `nombre` VARCHAR(100) NOT NULL,
  `hectareas` DECIMAL(10,2) NOT NULL,
  `sector` VARCHAR(150) NOT NULL,
  FOREIGN KEY (`id_productor`) REFERENCES `productores`(`id`) ON DELETE CASCADE,
  FOREIGN KEY (`id_parroquia`) REFERENCES `parroquias`(`id`)
) ENGINE=InnoDB;

-- 6. Tabla de Marcas (Con hash MD5 y Hash de Similitud 8x8)
CREATE TABLE IF NOT EXISTS `marcas` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `id_productor` INT NOT NULL UNIQUE,
  `nombre` VARCHAR(100) NOT NULL,
  `imagen_path` VARCHAR(255) NOT NULL,
  `imagen_hash` VARCHAR(32) NOT NULL,
  `imagen_similarity_hash` VARCHAR(64) NOT NULL,
  FOREIGN KEY (`id_productor`) REFERENCES `productores`(`id`) ON DELETE CASCADE
) ENGINE=InnoDB;

